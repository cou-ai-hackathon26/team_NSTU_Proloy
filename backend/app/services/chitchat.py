def get_chitchat_response(message: str) -> Optional[Tuple[str, float]]:
    """
    Checks if user input is an everyday Bangla conversational query.
    1. Defers explicit PCOS/PCOD clinical queries to grounded RAG for full citations.
    2. Normalizes conversational speech, slang, rural dialect, and Banglish.
    3. Matches against rich conversational intents.
    4. If no intent matched, defers to RAG for clinical/medical queries.
    Returns (response_text, confidence) if matched, or None.
    """
    if not message:
        return None

    # Step 0: Defer all medical, reproductive health, and clinical queries directly to RAG and LLM
    if is_medical_query(message):
        return None

    # Apply conversational dialect and phonetic normalization
    clean_msg = normalize_conversational_text(message)
    # Strip common punctuation
    clean_msg = re.sub(r"[?!.,।\-_~]", " ", clean_msg).strip()

    # Step 1: Match against comprehensive everyday natural intents
    for pattern, responses in CONVERSATIONAL_INTENTS:
        if re.search(pattern, clean_msg, re.IGNORECASE):
            reply = random.choice(responses)
            return reply, 0.95

    # Step 2: If no everyday intent matched, defer explicit clinical queries to RAG
    if is_medical_query(message):
        return None

    return None

