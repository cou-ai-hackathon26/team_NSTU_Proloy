def analyze_female_emotion(text: str) -> Optional[Dict[str, Any]]:
    """
    Analyzes user text across 13 core domains of female emotional distress in Bangladesh,
    identifying root causes and providing contextually tailored motivational stories & advice.
    """
    if not text:
        return None

    norm = normalize_bangla_text(text.lower())

    for cause_key, cause_data in EMOTIONAL_CAUSES.items():
        if re.search(cause_data["pattern"], norm, re.IGNORECASE):
            return {
                "cause_key": cause_key,
                "category_name": cause_data["category_name"],
                "story": cause_data["story"],
                "advice": cause_data["advice"]
            }

    return None

